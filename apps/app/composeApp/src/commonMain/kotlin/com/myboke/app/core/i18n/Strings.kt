/**
 * i18n ya papo hapo (§7.4): kila string iko hapa, composables hazitumii literals.
 * Kubadilisha lugha = kubadilisha `Lang` kwenye state; hakuna restart.
 */
/**
 * Lugha zinazotumika kwenye UI. `isRtl` inaamua mwelekeo wa layout (Arabic).
 * Kila lugha ina jina la asili (`nativeName`) ili mtumiaji aione kwa lugha yake.
 */
enum class Lang(
    val code: String,
    val nativeName: String,
    val englishName: String,
    val isRtl: Boolean = false,
) {
    SW("sw", "Kiswahili", "Swahili"),
    EN("en", "English", "English"),
    ES("es", "Español", "Spanish"),
    FR("fr", "Français", "French"),
    AR("ar", "العربية", "Arabic", isRtl = true);

    /** Nembo fupi inayoonekana kwenye kitufe cha lugha: SW, EN, ES, FR, AR. */
    val badge: String get() = code.uppercase()

    fun toggle(): Lang = entries[(ordinal + 1) % entries.size]

    companion object {
        fun fromCode(code: String?): Lang =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: SW
    }
}


